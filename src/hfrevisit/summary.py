"""Generate ``results/RESULTS_SUMMARY.md``: every number quoted in the
manuscript, read directly from the result tables (no manual transcription)."""

from __future__ import annotations

import json

import numpy as np
import pandas as pd

from .config import Paths


def _f(x, d=3):
    return "NA" if x is None or (isinstance(x, float) and not np.isfinite(x)) else f"{x:.{d}f}"


def _p(p):
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def _read(P: Paths, name: str) -> pd.DataFrame | None:
    f = P.tables / f"{name}.csv"
    return pd.read_csv(f) if f.exists() else None


def write_summary(P: Paths) -> str:
    L = ["# Results summary (auto-generated)", "",
         "Generated by `scripts/run_development.py --stages summary` from `results/tables/`.",
         "Do not edit by hand; quote numbers in the manuscript from this file.", ""]

    hist = P.logs / "run_history.jsonl"
    if hist.exists():
        L += ["Runs contributing to these tables (append-only history):", ""]
        for line in hist.read_text().splitlines():
            j = json.loads(line)
            if j.get("stage", "").startswith("development") and j.get("stages") != ["summary"]:
                L.append(f"- {j.get('timestamp')} | quick={j.get('quick')} | stages="
                         f"{','.join(j.get('stages', ['all']))} | MC splits={j.get('n_monte_carlo')} | "
                         f"CV repeats={j.get('n_cv_repeats')}")
        L.append("")

    a = _read(P, "leakage_A_followup_by_status")
    if a is not None:
        L += ["## Experiment A — follow-up by vital status", ""]
        for _, r in a.iterrows():
            L.append(f"- {r['group']}: n={r['n']}, median {r['median_days']:.0f} days "
                     f"(IQR {r['q1']:.0f}-{r['q3']:.0f}); <=30 d: {100 * r['share_<=30d']:.1f}%")
        L.append("")

    lk = _read(P, "leakage_BCD_per_split")
    pt = _read(P, "leakage_BCD_paired_tests")
    if lk is not None and pt is not None:
        L += ["## Experiments B-D — value of `time` (MCC, mean over splits)", "",
              "| Model | Baseline | Time only | Baseline + time | Baseline + shuffled time | Δ(base+time − base) [95% CI], p |",
              "|---|---|---|---|---|---|"]
        m = lk.groupby(["model", "feature_set"])["MCC"].mean().unstack()
        for model in m.index:
            r = pt[(pt.model == model) & (pt.metric == "MCC") & (pt.contrast == "baseline+time - baseline")].iloc[0]
            L.append(f"| {model} | {_f(m.loc[model, 'baseline'])} | {_f(m.loc[model, 'time only'])} | "
                     f"{_f(m.loc[model, 'baseline+time'])} | {_f(m.loc[model, 'baseline+shuffled time'])} | "
                     f"{_f(r.mean_diff)} [{_f(r.ci_low)}, {_f(r.ci_high)}], {_p(r.p)} |")
        L.append("")

    hz = _read(P, "leakage_E_horizon_summary")
    if hz is not None:
        L += ["## Experiment E — death within a fixed horizon, baseline predictors only", ""]
        for _, r in hz.iterrows():
            L.append(f"- tau={int(r['tau'])} d, {r['model']}: MCC {_f(r['MCC'])}, ROC AUC {_f(r['ROC_AUC'])} "
                     f"(eligible n={int(r['n_eligible'])}, event rate {100 * r['event_rate']:.1f}%)")
        L.append("")

    sim = _read(P, "simulation_summary")
    if sim is not None:
        L += ["## Simulation — leakage under null covariate effects (MCC mean [2.5-97.5 pct])", ""]
        for _, r in sim.iterrows():
            L.append(f"- {r['scenario']} | {r['model']} | {r['feature_set']}: "
                     f"{_f(r['MCC_mean'])} [{_f(r['MCC_p2.5'])}, {_f(r['MCC_p97.5'])}]")
        L.append("")

    rep = _read(P, "replication_summary")
    if rep is not None:
        L += ["## Replication of Chicco & Jurman (MCC mean)", "",
              "| Model | S1 (incl. time) | S2 (baseline) | S3 (EF+SC) |", "|---|---|---|---|"]
        w = rep.pivot(index="model", columns="scenario", values="MCC_mean")
        w = w[sorted(w.columns)]
        for model, r in w.sort_values(w.columns[0], ascending=False).iterrows():
            L.append(f"| {model} | " + " | ".join(_f(v) for v in r.values) + " |")
        L.append("")

    sv = _read(P, "survival_cv_summary")
    if sv is not None:
        L += ["## Survival models — repeated 5-fold CV (mean [2.5-97.5 pct over folds])", "",
              "| Model | Harrell C | Uno C | AUC 90 d | AUC 180 d | Brier 90 d | IBS (KM null) |",
              "|---|---|---|---|---|---|---|"]
        for _, r in sv.iterrows():
            def ci(c):
                return f"{_f(r[c])} [{_f(r[c + '_p2.5'])}, {_f(r[c + '_p97.5'])}]" if c in r and pd.notna(r[c]) else "NA"
            L.append(f"| {r['model']} | {ci('harrell_c')} | {ci('uno_c')} | {ci('auc_90d')} | {ci('auc_180d')} | "
                     f"{_f(r.get('brier_90d'))} | {_f(r.get('ibs'))} ({_f(r.get('ibs_km_null'))}) |")
        L.append("")
    pc = _read(P, "survival_paired_comparison")
    if pc is not None:
        L += ["Paired comparison vs Cox PH (corrected resampled t-test):", ""]
        for _, r in pc.iterrows():
            L.append(f"- {r['metric']}: {r['model']} − Cox PH = {_f(r.mean_diff)} "
                     f"[{_f(r.ci_low)}, {_f(r.ci_high)}], p={_p(r.p)}")
        L.append("")

    bo = _read(P, "survival_bootstrap_optimism")
    if bo is not None:
        L += ["Bootstrap internal validation (Harrell):", ""]
        for _, r in bo.iterrows():
            L.append(f"- {r['model']}: apparent C {_f(r.apparent_c)}, optimism {_f(r.optimism)}, "
                     f"corrected C {_f(r.corrected_c)}; calibration slope {_f(r.calibration_slope, 2)} "
                     f"[{_f(r['calibration_slope_p2.5'], 2)}, {_f(r['calibration_slope_p97.5'], 2)}] "
                     f"(B={int(r.n_boot)})")
        L.append("")

    hr = _read(P, "table2_cox_hazard_ratios")
    if hr is not None:
        L += ["## Cox hazard ratios (full cohort)", ""]
        for _, r in hr.iterrows():
            L.append(f"- {r['variable']} ({r['unit']}): HR {r['HR']:.2f} ({r['CI_low']:.2f}-{r['CI_high']:.2f}), p={_p(r['p'])}")
        ph = _read(P, "table_s_ph_schoenfeld")
        if ph is not None:
            viol = ph[ph["p"] < 0.05]["covariate"].tolist()
            L.append(f"- PH assumption (Schoenfeld, p<0.05): {', '.join(viol) if viol else 'none'}")
        L.append("")

    cal = _read(P, "calibration_oof_horizon_summary")
    if cal is not None:
        L += ["## Out-of-fold calibration at horizon", ""]
        for _, r in cal.iterrows():
            L.append(f"- {r['model']}, {int(r['tau'])} d: predicted {100 * r['mean_predicted_risk']:.1f}% vs "
                     f"observed (KM) {100 * r['observed_km_risk']:.1f}%, O/E {_f(r['observed_expected_ratio'], 2)}")
        L.append("")

    ss = _read(P, "sample_size_riley")
    if ss is not None:
        r = ss.iloc[0]
        L += ["## Sample-size adequacy (Riley et al.)", "",
              f"- Apparent Cox-Snell R² = {_f(r['r2_cs'])}; minimum n = {int(r['minimum_n'])} "
              f"(shrinkage {int(r['criterion_i_shrinkage'])}, optimism {int(r['criterion_ii_optimism'])}, "
              f"precision {int(r['criterion_iii_precision'])}) vs available n = {int(r['n_available'])}",
              f"- Expected shrinkage at the available n: {_f(r['expected_shrinkage_at_n'])}", ""]

    sub = _read(P, "table3_subgroup_cindex")
    if sub is not None:
        L += ["## Subgroups — out-of-fold Harrell C [95% bootstrap CI]", ""]
        for _, r in sub.iterrows():
            flag = " (exploratory, <20 events)" if r["exploratory"] else ""
            L.append(f"- {r['model']} | {r['subgroup']} (n={r['n']}, events={r['events']}): "
                     f"{_f(r.get('estimate'))} [{_f(r.get('ci_low'))}, {_f(r.get('ci_high'))}]{flag}")
        L.append("")

    out = P.results / "RESULTS_SUMMARY.md"
    out.write_text("\n".join(L))
    return str(out)
